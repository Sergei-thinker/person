HistoryItem = Tuple[str, str]


def build_messages(history: List[HistoryItem]) -> List[dict]:
    # Keep last 16 messages (approx 8 pairs) - увеличено с 8 для лучшего контекста
    trimmed = history[-16:]
    messages = [{"role": "system", "content": system_prompt}]
    for role, content in trimmed:
        messages.append({"role": role, "content": content})
    return messages


